export function enrichPhaseGuides(
  templateId: string,
  phases: { guide?: string }[],
): void {
  const guides = TEMPLATE_PHASE_GUIDES[templateId];
  if (!guides) return;
  phases.forEach((p, i) => {
    if (!p.guide && guides[i]) p.guide = guides[i];
  });
}
