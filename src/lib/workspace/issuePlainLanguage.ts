const HEADER_REPLACEMENTS: Array<[string, string]> = [
  ["【フェーズのゴール】", "【この段階のねらい】"],
  ["【フェーズのガイド】", "【ヒント】"],
  ["【この課題】", "【やること】"],
  ["【考えること】", "【考えてみること】"],
];

export function simplifyIssueText(text: string): string {
  let out = text.trim();
  if (!out) return out;
  for (const [re, replacement] of WORD_REPLACEMENTS) {
    out = out.replace(re, replacement);
  }
  for (const [from, to] of HEADER_REPLACEMENTS) {
    out = out.split(from).join(to);
  }
  return out.replace(/\s{2,}/g, " ").trim();
}
